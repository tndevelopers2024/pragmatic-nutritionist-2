export function findRecipeBySlug(slug) {
  if (!slug) return null
  const decoded = decodeURIComponent(slug).toLowerCase()
  return (
    RECIPES.find(
      (r) =>
        r.slug.toLowerCase() === decoded ||
        r.aliases?.some((alias) => alias.toLowerCase() === decoded)
    ) || null
  )
}
